export type ArticleCategory = 'ai' | 'technology' | 'science' | 'research';

export type ArticleType = 
  | 'breaking'
  | 'analysis'
  | 'deep-dive'
  | 'model-report'
  | 'benchmark-report'
  | 'research-explained'
  | 'discovery'
  | 'industry-watch';

export interface ThreeQuestions {
  whatHappened: string;
  whyItMatters: string;
  whatsNext: string;
}

export interface Article {
  id: string;
  slug: string;
  title: string;
  subtitle: string;
  category: ArticleCategory;
  articleType: ArticleType;
  signalRating: number; // 1-100 score indicating technical/scientific significance over hype
  author: {
    name: string;
    role: string;
    avatar: string;
    verified: boolean;
    website?: string;
    github?: string;
    substack?: string;
    bio?: string;
  };
  publishedAt: string;
  readTimeMinutes: number;
  coverImage: string;
  coverImageAlt?: string;
  tags: string[];
  threeQuestions: ThreeQuestions;
  keyTakeaways: string[];
  content: string[]; // paragraph blocks / markdown
  technicalSpecs?: Record<string, string>;
  relatedModelId?: string;
  relatedBenchmarkId?: string;
  relatedPaperId?: string;
  audioDuration?: string; // e.g. "3m 40s"
  citations?: { title: string; url: string; source: string }[];
  isHero?: boolean;
  isFeatured?: boolean;
}

/** Heavy per-article fields, code-split into one lazy chunk per article (see vite.articleSplit.ts). */
export interface ArticleBody {
  keyTakeaways: string[];
  content: string[];
  technicalSpecs?: Record<string, string>;
  citations?: { title: string; url: string; source: string }[];
}

/** Lightweight article shape used by cards, lists, search and routing. */
export type ArticleSummary = Omit<Article, keyof ArticleBody>;

export interface SourceRef {
  label: string;
  url: string;
}

/** Generated by scripts/build_model_data.py from dated public sources. Missing data stays missing. */
export interface AIModel {
  id: string;
  name: string;
  developer: string;
  releaseDate: string; // "September 2026" or "Not listed"
  releaseDateSource?: string | null;
  modelType: 'Reasoning' | 'Multimodal Foundation' | 'Code & Agent' | 'Open Weights' | 'Compact / Edge';
  modalities: string[];
  contextWindow: string; // e.g. "1M tokens", "Not listed"
  contextTokens?: number | null;
  parameters: string; // e.g. "671B total, 37B active (MoE)", "Not disclosed"
  pricing: {
    inputPer1M: number | null; // null = no public per-token price
    outputPer1M: number | null;
    cachedInputPer1M?: number | null;
    source?: string;
    note?: string;
  };
  openSourceStatus: 'Open Weights' | 'Proprietary API';
  license: string;
  hardwareRequirements: string; // how you can run it: hosted API, open weights, restricted access
  benchmarks: {
    benchmarkName: string;
    score: number | string;
    unit?: string;
    vsPreviousGen: string; // run details: rank, variant, harness, date
    sourceUrl?: string;
  }[];
  keyImprovements: string[];
  knownLimitations: string[];
  realWorldApplications: string[];
  architectureNotes: string;
  summary?: string;
  link?: string;
  access?: string;
  arenaRank?: number; // rank on arena.ai text leaderboard (all entries, incl. models we do not track)
  arenaElo?: number;
  arenaVotes?: number;
  arenaCI?: number; // +/- score interval
  arenaVariant?: string; // arena.ai entry used (e.g. "claude-opus-5.5-high")
  preRelease?: boolean;
  // Artificial Analysis indexes (best setting per model); credit artificialanalysis.ai wherever shown
  aaIntelligence?: number;
  aaCoding?: number;
  aaAgentic?: number;
  aaVariant?: string; // AA setting behind the Intelligence score, e.g. "GPT-6 Astra (Max)"
  sources?: SourceRef[];
  dataAsOf?: string;
}

export interface LeaderboardEntry {
  rank: number;
  modelName: string;
  developer: string;
  score: number;
  date: string;
  modelId?: string; // set when the model is in our registry
  costPerRun?: string;
  note?: string;
}

export interface Benchmark {
  id: string;
  name: string;
  shortName?: string;
  category: 'Coding & Agents' | 'Reasoning & Logic' | 'General Knowledge' | 'Mathematics' | 'Safety & Alignment' | 'Overall Arena Elo' | 'Cost-Efficiency & Pareto';
  description: string;
  whatItMeasures: string;
  whyItMatters: string;
  potentialLimitations: string; // caveats, contamination risks, synthetic gap
  scoreUnit?: string;
  scoreMetricName?: string;
  sourceUrl?: string;
  dataAsOf?: string;
  leaderboard: LeaderboardEntry[];
  /** Optional wider list behind a toggle (e.g. all runs, all priced models). */
  altView?: {
    baseLabel: string;
    label: string;
    description: string;
    leaderboard: LeaderboardEntry[];
  };
  /** Price vs score board only: one point per priced model for the scatter chart. */
  pricePoints?: PriceScorePoint[];
}

/** One model on the price vs Arena score chart. Price is blended USD per 1M tokens. */
export interface PriceScorePoint {
  modelId: string;
  modelName: string;
  developer: string;
  price: number;
  score: number;
  frontier: boolean;
  preRelease?: boolean;
}

/** Head-to-head page. Generated by scripts/build_model_data.py; every sentence is derived from registry data. */
export interface PresetShowdown {
  slug: string;
  name: string;
  shortTitle: string;
  category: 'Frontier Flagships' | 'Cost & Pareto' | 'Open Weights';
  modelIdA: string;
  modelIdB: string;
  seoTitle: string;
  seoDescription: string;
  executiveVerdict: string;
  verdictA: { title: string; points: string[] };
  verdictB: { title: string; points: string[] };
  faqs: { question: string; answer: string }[];
}

/** Decision-guide pick chosen by a stated rule over registry data. */
export interface GuidePick {
  id: string;
  title: string;
  rule: string;
  modelId: string;
  modelName: string;
  developer: string;
  metric: string;
  price: string;
}

